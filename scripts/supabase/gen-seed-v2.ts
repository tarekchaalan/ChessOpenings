/**
 * Writes, from the shipped dataset and legacy map (ADR 0004 step 2):
 *   supabase/seed.sql                     reference data, re-runnable on every dataset update
 *   scripts/supabase/seed-legacy-v1.sql   one-time v1 → v2 staging rows (before migrate-v2-data.sql)
 * Local files only: applying them remotely needs the owner's approval (see
 * scripts/supabase/dry-run-v2.ts for the tested order).
 *
 *   npx tsx scripts/supabase/gen-seed-v2.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseDatasetV2 } from "../../src/lib/openings";
import { buildSeedV2, legacySql, seedSql } from "../../src/lib/server/seed-v2";

const ROOT = join(__dirname, "../..");
const t0 = Date.now();
const meta = JSON.parse(readFileSync(join(ROOT, "public/data/openings.v2.meta.json"), "utf8"));
const raw = JSON.parse(readFileSync(join(ROOT, "public/data/openings.v2.json"), "utf8"));
const legacy = JSON.parse(readFileSync(join(ROOT, "public/data/legacy-map.v1.json"), "utf8"));
const ds = parseDatasetV2(raw, meta.outputHash);
const seed = buildSeedV2(ds, legacy, { hash: meta.outputHash });
const sql = seedSql(seed, [
  "Generated by scripts/supabase/gen-seed-v2.ts — DO NOT EDIT.",
  `Dataset outputHash ${meta.outputHash}`,
  "Reference data + v1 → v2 staging (ADR 0004). Applied after migrations/0004_v2_schema.sql.",
]);
writeFileSync(join(ROOT, "supabase/seed.sql"), sql);
const legacySqlText = legacySql(seed, [
  "Generated by scripts/supabase/gen-seed-v2.ts — DO NOT EDIT.",
  `Dataset outputHash ${meta.outputHash}`,
  "One-time v1 → v2 staging rows (ADR 0004). Order: 0004 → supabase/seed.sql → this → migrate-v2-data.sql.",
]);
writeFileSync(join(ROOT, "scripts/supabase/seed-legacy-v1.sql"), legacySqlText);
console.log(
  `seed.sql: ${seed.edges.length} edges (${seed.edges.filter((e) => e.is_ext).length} ext), ${seed.lines.length} lines, ` +
    `(${(sql.length / 1e6).toFixed(1)} MB); seed-legacy-v1.sql: ${seed.legacyOpenings.length} legacy openings, ${seed.rowAnswers.length} row answers, ` +
    `${seed.answers.length} position answers (${(legacySqlText.length / 1e6).toFixed(1)} MB); ${((Date.now() - t0) / 1000).toFixed(1)} s`
);
