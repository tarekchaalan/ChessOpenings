/**
 * Writes, from the shipped dataset and legacy map (ADR 0004 step 2), as
 * numbered SQL files of < 1 MB each (applied in name order):
 *   supabase/seed/*.sql                 reference data, re-runnable on every dataset update
 *                                       (config.toml [db.seed] sql_paths → `supabase db reset`)
 *   scripts/supabase/seed-legacy-v1/*.sql   one-time v1 → v2 staging rows (before migrate-v2-data.sql)
 * Local files only: applying them remotely needs the owner's approval (see
 * scripts/supabase/dry-run-v2.ts for the tested order).
 *
 *   npx tsx scripts/supabase/gen-seed-v2.ts
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseDatasetV2 } from "../../src/lib/openings";
import { buildSeedV2, legacyFiles, seedFiles, type SqlFile } from "../../src/lib/server/seed-v2";

const ROOT = join(__dirname, "../..");
const t0 = Date.now();
const meta = JSON.parse(readFileSync(join(ROOT, "public/data/openings.v2.meta.json"), "utf8"));
const raw = JSON.parse(readFileSync(join(ROOT, "public/data/openings.v2.json"), "utf8"));
const legacy = JSON.parse(readFileSync(join(ROOT, "public/data/legacy-map.v1.json"), "utf8"));
const ds = parseDatasetV2(raw, meta.outputHash);
const seed = buildSeedV2(ds, legacy, { hash: meta.outputHash });

/** Replace a directory's generated .sql files (stale chunks must not linger). */
function writeDir(dir: string, files: SqlFile[]): number {
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) if (f.endsWith(".sql")) rmSync(join(dir, f));
  let bytes = 0;
  for (const f of files) {
    writeFileSync(join(dir, f.name), f.sql);
    bytes += Buffer.byteLength(f.sql);
  }
  return bytes;
}

const header = (what: string) => ["Generated by scripts/supabase/gen-seed-v2.ts — DO NOT EDIT.", `Dataset outputHash ${meta.outputHash}`, what];
const ref = seedFiles(seed, header("v2 reference data (ADR 0004). Apply the files in name order, after migrations/0004_v2_schema.sql."));
const stage = legacyFiles(seed, header("One-time v1 → v2 staging rows (ADR 0004). Order: 0004 → supabase/seed/*.sql → these, in name order → migrate-v2-data.sql."));
const refBytes = writeDir(join(ROOT, "supabase/seed"), ref);
const stageBytes = writeDir(join(ROOT, "scripts/supabase/seed-legacy-v1"), stage);
console.log(
  `supabase/seed: ${ref.length} files, ${(refBytes / 1e6).toFixed(1)} MB (${seed.edges.length} edges, ${seed.edges.filter((e) => e.is_ext).length} ext; ${seed.lines.length} lines); ` +
    `scripts/supabase/seed-legacy-v1: ${stage.length} files, ${(stageBytes / 1e6).toFixed(1)} MB (${seed.legacyOpenings.length} openings, ${seed.rowAnswers.length} row answers, ${seed.answers.length} position answers); ` +
    `largest file ${Math.max(...[...ref, ...stage].map((f) => Buffer.byteLength(f.sql))).toLocaleString("en-US")} B; ${((Date.now() - t0) / 1000).toFixed(1)} s`
);
