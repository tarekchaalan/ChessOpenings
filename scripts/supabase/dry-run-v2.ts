// ── psql helpers ───────────────────────────────────────────────────────────
const PSQL = ["-X", "-q", "-v", "ON_ERROR_STOP=1", "-A", "-t"];
function sql(q: string, target = url): string {
  return execFileSync("psql", [...PSQL, target, "-c", q], { encoding: "utf8", maxBuffer: 1 << 28 }).trim();
}
function file(path: string): { ms: number; notices: string } {
  const t = Date.now();
  const r = spawnSync("psql", [...PSQL, url, "-f", path], { encoding: "utf8", maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(`${path}:\n${r.stderr}`);
  return { ms: Date.now() - t, notices: r.stderr.trim() };
}
/** expect the statement to fail (permission checks) */
function denied(q: string): string | null {
  const r = spawnSync("psql", [...PSQL, url, "-c", q], { encoding: "utf8" });
  return r.status === 0 ? null : (r.stderr.split("\n").find((l) => l.startsWith("ERROR")) ?? r.stderr).trim();
}
const json = <T>(q: string): T => JSON.parse(sql(`select coalesce(json_agg(t), '[]') from (${q}) t`) || "[]") as T;
const lit = (s: string | null) => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(lit).join(",")}]::text[]`;

const checks: { name: string; ok: boolean; detail: string }[] = [];
const check = (name: string, ok: boolean, detail = "") => {
  checks.push({ name, ok, detail });
  console.log(`${ok ? "✓" : "✗"} ${name}${detail ? ` — ${detail}` : ""}`);
};

